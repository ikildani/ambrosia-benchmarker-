/**
 * Filter extended deals by therapeutic area.
 */
export function getExtendedDealsByTA(therapeuticArea: string): ExtendedComparableDeal[] {
  return EXTENDED_COMPARABLE_DEALS.filter(d => d.therapeuticArea === therapeuticArea);
}

/**
 * Filter extended deals by deal classification flags.
 */
export function getExtendedDealsByType(options: {
  combinationTherapy?: boolean;
  geographicSpecific?: boolean;
  dealType?: ExtendedComparableDeal['dealType'];
}): ExtendedComparableDeal[] {
  return EXTENDED_COMPARABLE_DEALS.filter(d => {
    if (options.combinationTherapy !== undefined && d.combinationTherapy !== options.combinationTherapy) return false;
    if (options.geographicSpecific !== undefined && d.geographicSpecific !== options.geographicSpecific) return false;
    if (options.dealType !== undefined && d.dealType !== options.dealType) return false;
    return true;
  });
}

/**
 * Find the most relevant extended deals for given inputs, scored by match quality.
 */
export function findRelevantExtendedDeals(
  inputs: {
    therapeuticArea?: string;
    modality?: string;
    indication?: string;
    territory?: string;
    phase?: string;
    combinationTherapy?: boolean;
  },
  maxDeals: number = 5
): ExtendedComparableDeal[] {
  const scored = EXTENDED_COMPARABLE_DEALS.map(deal => {
    let score = 0;

    // Therapeutic area match (weight: 3)
    if (inputs.therapeuticArea && deal.therapeuticArea === inputs.therapeuticArea) {
      score += 3;
    }

    // Modality match (weight: 4)
    if (inputs.modality && deal.modality === inputs.modality) {
      score += 4;
    }

    // Indication match (weight: 3)
    if (inputs.indication && deal.indication_specific === inputs.indication) {
      score += 3;
    }

    // Territory match (weight: 2)
    if (inputs.territory && deal.territory === inputs.territory) {
      score += 2;
    }

    // Phase match (weight: 2)
    if (inputs.phase && deal.phase === inputs.phase) {
      score += 2;
    }

    // Combination therapy match (weight: 2)
    if (inputs.combinationTherapy !== undefined && deal.combinationTherapy === inputs.combinationTherapy) {
      score += 2;
    }

    return { deal, score };
  });

  return scored
    .filter(s => s.score >= 3)
    .sort((a, b) => b.score - a.score)
    .slice(0, maxDeals)
    .map(s => s.deal);
}
