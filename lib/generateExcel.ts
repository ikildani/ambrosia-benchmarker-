import * as XLSX from 'xlsx';
import { CalculationResult, formatCurrency } from './calculations';

export interface PartnerForExcel {
  company_name: string;
  match_score: number;
  match_reasons: { reason: string; strength: string }[];
  deals_last_12mo: number;
  hq_country: string | null;
}

export function generateExcelReport(
  result: CalculationResult,
  inputs?: {
    modality: string;
    phase: string;
    indication: string;
    territory: string;
  },
  partners?: PartnerForExcel[]
): void {
  const { terms, tieredRoyalties, dealRecommendation, negotiationInsight, modifiers, labels } = result;

  const wb = XLSX.utils.book_new();

  // Sheet 1: Executive Summary
  const summaryData = [
    ['Biotech Deal Analysis Report'],
    ['Generated by Ambrosia Ventures Deal Calculator'],
    [`Report Date: ${new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' })}`],
    [''],
    ['ASSET PROFILE'],
    ['Development Phase', labels.phase],
    ['Modality', labels.modality],
    ['Indication', labels.indication],
    ['Territory', inputs?.territory || 'Not specified'],
    [''],
    ['RECOMMENDED DEAL STRUCTURE'],
    ['Upfront %', `${dealRecommendation.upfrontPercent}%`],
    ['Milestones %', `${dealRecommendation.milestonePercent}%`],
    ['Rationale', dealRecommendation.rationale],
    [''],
    ['NEGOTIATION INSIGHT'],
    [negotiationInsight],
  ];

  const summarySheet = XLSX.utils.aoa_to_sheet(summaryData);

  // Set column widths for summary
  summarySheet['!cols'] = [{ wch: 25 }, { wch: 60 }];

  XLSX.utils.book_append_sheet(wb, summarySheet, 'Summary');

  // Sheet 2: Deal Terms
  const termsData = [
    ['ESTIMATED DEAL TERMS'],
    [''],
    ['Metric', 'Low', 'Median', 'High', 'Notes'],
    ['Upfront Payment', formatCurrency(terms.upfront.low), formatCurrency(terms.upfront.median), formatCurrency(terms.upfront.high), 'Guaranteed payment at signing'],
    ['Development Milestones', formatCurrency(terms.devMilestones.low), formatCurrency(terms.devMilestones.median), formatCurrency(terms.devMilestones.high), 'Upon clinical milestones'],
    ['Regulatory Milestones', formatCurrency(terms.regMilestones.low), formatCurrency(terms.regMilestones.median), formatCurrency(terms.regMilestones.high), 'Upon FDA/EMA approval'],
    ['Commercial Milestones', formatCurrency(terms.commMilestones.low), formatCurrency(terms.commMilestones.median), formatCurrency(terms.commMilestones.high), 'Upon sales thresholds'],
    ['Total Deal Value', formatCurrency(terms.totalDealValue.low), formatCurrency(terms.totalDealValue.median), formatCurrency(terms.totalDealValue.high), 'If all milestones achieved'],
    [''],
    ['TIERED ROYALTIES'],
    [''],
    ['Sales Tier', 'Low Rate', 'High Rate', 'Threshold', ''],
    ['Base', `${tieredRoyalties.base.low}%`, `${tieredRoyalties.base.high}%`, '<$500M annual sales', ''],
    ['Mid-Tier', `${tieredRoyalties.midTier.low}%`, `${tieredRoyalties.midTier.high}%`, '$500M - $1B annual sales', ''],
    ['High-Tier', `${tieredRoyalties.highTier.low}%`, `${tieredRoyalties.highTier.high}%`, '>$1B annual sales', ''],
  ];

  const termsSheet = XLSX.utils.aoa_to_sheet(termsData);
  termsSheet['!cols'] = [{ wch: 25 }, { wch: 15 }, { wch: 15 }, { wch: 15 }, { wch: 30 }];
  XLSX.utils.book_append_sheet(wb, termsSheet, 'Deal Terms');

  // Sheet 3: Modifiers Applied
  if (modifiers.length > 0) {
    const modifiersData = [
      ['ADJUSTMENTS APPLIED'],
      [''],
      ['Factor', 'Impact', 'Percentage Change'],
      ...modifiers.map(mod => [
        mod.name,
        mod.multiplier > 1 ? 'Positive' : mod.multiplier < 1 ? 'Negative' : 'Neutral',
        `${mod.multiplier > 1 ? '+' : ''}${Math.round((mod.multiplier - 1) * 100)}%`
      ]),
      [''],
      ['Note: These adjustments were applied based on your specific asset profile'],
    ];

    const modifiersSheet = XLSX.utils.aoa_to_sheet(modifiersData);
    modifiersSheet['!cols'] = [{ wch: 35 }, { wch: 15 }, { wch: 20 }];
    XLSX.utils.book_append_sheet(wb, modifiersSheet, 'Adjustments');
  }

  // Sheet 4: Partner Matches (if available)
  if (partners && partners.length > 0) {
    const partnersData = [
      ['POTENTIAL PARTNERS'],
      [''],
      ['Company', 'Match Score', 'Recent Deals (12mo)', 'HQ Country', 'Key Match Reasons'],
      ...partners.map(p => [
        p.company_name,
        `${p.match_score}%`,
        p.deals_last_12mo.toString(),
        p.hq_country || 'N/A',
        p.match_reasons.slice(0, 3).map(r => r.reason).join('; ')
      ]),
    ];

    const partnersSheet = XLSX.utils.aoa_to_sheet(partnersData);
    partnersSheet['!cols'] = [{ wch: 30 }, { wch: 15 }, { wch: 20 }, { wch: 15 }, { wch: 30 }];
    XLSX.utils.book_append_sheet(wb, partnersSheet, 'Partners');
  }

  // Sheet 5: Methodology & Disclaimer
  const methodologyData = [
    ['METHODOLOGY'],
    [''],
    ['This analysis was generated using Ambrosia Ventures\' proprietary benchmarking model.'],
    [''],
    ['Data Sources:'],
    ['• Publicly disclosed deal terms (SEC filings, press releases)'],
    ['• Industry benchmark reports and market intelligence'],
    ['• Recent transaction activity and emerging trends'],
    [''],
    ['The algorithm weighs multiple factors including:'],
    ['• Development phase and clinical data quality'],
    ['• Therapeutic modality and mechanism of action'],
    ['• Indication, patient population, and unmet need'],
    ['• Territory scope and competitive landscape'],
    ['• Regulatory designations and market dynamics'],
    [''],
    ['IMPORTANT DISCLAIMER'],
    [''],
    ['These estimates are for informational and planning purposes only.'],
    ['This does not constitute financial, legal, investment, or professional advice.'],
    ['Actual deal terms vary significantly based on asset-specific factors,'],
    ['market conditions, negotiation dynamics, and other variables.'],
    [''],
    ['Consult qualified professionals before making business decisions.'],
    [''],
    ['© Ambrosia Ventures - calculator.ambrosiaventures.co'],
  ];

  const methodologySheet = XLSX.utils.aoa_to_sheet(methodologyData);
  methodologySheet['!cols'] = [{ wch: 70 }];
  XLSX.utils.book_append_sheet(wb, methodologySheet, 'Methodology');

  // Generate filename with timestamp
  const timestamp = new Date().toISOString().slice(0, 10);
  const filename = `deal-analysis-${labels.modality.toLowerCase().replace(/\s+/g, '-')}-${timestamp}.xlsx`;

  // Write file
  XLSX.writeFile(wb, filename);
}
